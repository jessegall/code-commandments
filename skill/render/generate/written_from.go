package main

import (
	"crypto/sha256"
	"encoding/hex"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strconv"
)

// mark is where the key the published skills were written from is kept, beside them.
const mark = published + "/.written-from"

// writtenFrom is the key everything the generator reads adds up to. Writing the skills costs minutes — the fixtures
// of five engines are parsed and every detector of each is run over them, which starts a C# bridge and builds a
// Python environment — and the pre-commit hook pays it on every commit, including the ones that cannot change a
// single generated byte. So the generator asks first whether anything it reads has moved.
//
// Two things can change what it writes, and only two. The first is this very program, since every skill, every sin
// and every line of the renderer is compiled into it; its own bytes answer for all of them, and Go builds the same
// source into the same binary, so the key is stable while the source is. The second is the fixtures, which the
// worked examples are carved from, and those are read as they are on disk.
//
// The skills it WROTE go into the key as well, which is what keeps --check honest: a published document edited by
// hand, or reverted, must be found stale even though nothing it was written from has moved.
//
// What this deliberately does NOT do is guess which files matter. A list of paths that affect the output is a guess
// that rots the first time someone adds a source the renderer reads; the binary and the fixtures are what it reads,
// so they are what it hashes.
func writtenFrom(fixtures string) (string, error) {
	sum := sha256.New()

	binary, err := os.Executable()
	if err != nil {
		return "", err
	}
	if err := hashFile(sum, binary); err != nil {
		return "", err
	}

	if err := hashTree(sum, fixtures); err != nil {
		return "", err
	}

	// The mark itself is left out, since it is written after the key is taken and would answer a key of its own.
	if err := hashTree(sum, published, mark); err != nil && !os.IsNotExist(err) {
		return "", err
	}

	return hex.EncodeToString(sum.Sum(nil)), nil
}

// hashFile folds the file's bytes into the sum.
func hashFile(sum io.Writer, path string) error {
	file, err := os.Open(path)
	if err != nil {
		return err
	}
	defer file.Close()

	_, err = io.Copy(sum, file)

	return err
}

// hashTree folds every file under the folder into the sum, less the ones named apart, by path in one order, so the
// same tree answers the same key however the filesystem lists it. A file's size goes in beside its name, which is
// what tells two trees apart when a file was emptied or filled rather than renamed.
func hashTree(sum io.Writer, root string, apart ...string) error {
	var paths []string
	sizes := map[string]int64{}

	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		if slices.Contains(apart, path) {
			return nil
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		paths = append(paths, path)
		sizes[path] = info.Size()

		return nil
	})
	if err != nil {
		return err
	}

	sort.Strings(paths)

	for _, path := range paths {
		if _, err := io.WriteString(sum, path+"\x00"+strconv.FormatInt(sizes[path], 10)+"\x00"); err != nil {
			return err
		}
		if err := hashFile(sum, path); err != nil {
			return err
		}
	}

	return nil
}

// alreadyWrittenFrom says whether the published skills were written from this very key, so there is nothing to do.
func alreadyWrittenFrom(key string) bool {
	written, err := os.ReadFile(mark)

	return err == nil && string(written) == key
}

// rememberWrittenFrom keeps the key beside the skills it wrote, so the next run can see at once that nothing moved.
// A key that cannot be written is no failure of the generation: the skills are written, and the next run simply
// does the work again.
func rememberWrittenFrom(key string) {
	if err := os.MkdirAll(filepath.Dir(mark), 0o755); err == nil {
		os.WriteFile(mark, []byte(key), 0o644)
	}
}

// forgetWrittenFrom drops the key, which is what a run that wrote nothing it was asked to write must do rather than
// claim the skills stand for sources they do not.
func forgetWrittenFrom() {
	os.Remove(mark)
}
