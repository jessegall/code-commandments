package golang_test

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"

	"github.com/jessegall/code-commandments/bridge/gotree"
	"github.com/jessegall/code-commandments/contract"
	"github.com/jessegall/code-commandments/engine"
	_ "github.com/jessegall/code-commandments/engine/golang"
)

func codebaseOf(t *testing.T, files map[string]string) *engine.Codebase {
	t.Helper()
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	for name, source := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(source), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	var written bytes.Buffer
	if err := gotree.Write(&written, []string{root}, nil); err != nil {
		t.Fatal(err)
	}
	stream, err := contract.ReadAll(bytes.NewReader(written.Bytes()))
	if err != nil {
		t.Fatalf("the stream breaks the contract: %v", err)
	}

	return engine.Load(stream)
}

func fileNamed(t *testing.T, codebase *engine.Codebase, name string) *engine.File {
	t.Helper()
	for _, file := range codebase.Files() {
		if filepath.Base(file.Path) == name {
			return file
		}
	}
	t.Fatalf("the codebase holds no %s", name)

	return nil
}

func TestAGeneratedFileIsReadAndNeverReportedOn(t *testing.T) {
	codebase := codebaseOf(t, map[string]string{
		"go.mod":      "module example.com/shop\n",
		"schema.go":   "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage shop\n\ntype Row struct{ Total int }\n",
		"cart.go":     "package shop\n\nfunc total(row Row) int { return row.Total }\n",
		"mentions.go": "package shop\n\n// Code generated is a phrase this comment merely holds. DO NOT EDIT.\nfunc note() {}\n",
	})

	if !fileNamed(t, codebase, "schema.go").IsFrozen() {
		t.Error("a file carrying Go's own generated marker is not frozen")
	}
	if fileNamed(t, codebase, "cart.go").IsFrozen() {
		t.Error("a hand-written file is frozen")
	}
	if fileNamed(t, codebase, "mentions.go").IsFrozen() {
		t.Error("a comment deeper in a file froze it, where the marker stands before the package clause")
	}
}

func TestAGeneratedFileStillResolvesForTheRest(t *testing.T) {
	codebase := codebaseOf(t, map[string]string{
		"go.mod":    "module example.com/shop\n",
		"schema.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage shop\n\ntype Row struct{ Total int }\n",
		"cart.go":   "package shop\n\nfunc total(row Row) int { return row.Total }\n",
	})

	file := fileNamed(t, codebase, "cart.go")
	for _, node := range file.File.Nodes() {
		if node.Resolved != nil && node.Resolved.Text == "example.com/shop.Row" {
			return
		}
	}
	t.Error("a type a generated file declares did not resolve in the file that uses it")
}
